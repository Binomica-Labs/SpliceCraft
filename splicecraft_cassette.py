"""splicecraft_cassette — eukaryotic transcription-unit assembler (layer L3).

The nuclear-expression counterpart to `splicecraft_biology._assemble_operon`.
That function assembles a BACTERIAL operon (one promoter, many RBS+CDS, one
terminator) and its hard problem is translation initiation — each RBS has to
be reverse-designed against its real upstream context. A plant nuclear
transcription unit has the opposite shape: ONE coding block, but a stack of
positional regulatory parts around it (promoter / 5'UTR / intron / signal
peptide / CDS / C-tag / terminator), and its hard problems are

  * **frame** — the signal peptide, the mature CDS and any C-terminal tag are
    one continuous ORF spread across three separately-sourced parts, so a part
    whose length is not a multiple of 3 frameshifts everything downstream of
    it. Silent in a plasmid map, fatal in planta.
  * **motif hygiene** — the coding block has to lose polyadenylation signals,
    mRNA instability motifs, cryptic splice sites and the assembly enzyme's
    own recognition sites, WITHOUT changing the protein.
  * **assembly-scar compatibility** — Type IIS overhangs have to chain
    promoter→UTR→CDS→tag→terminator and be mutually distinct, or the one-pot
    reaction misassembles.
  * **internal repeats** — a clonally-propagated host (any vegetatively
    multiplied crop) cannot segregate away a silenced insert, so
    a long direct repeat inside one T-DNA is a permanent liability rather than
    an F2 inconvenience.

This module answers those four and nothing else: it is a PURE assembler over
already-retrieved parts. It does not fetch sequence, pick promoters, or decide
biology — callers do that and hand in the parts.

`_assemble_expression_cassette` mirrors `_assemble_operon`'s contract on
purpose: same JSON-serialisable dict return, same "layout TILES the sequence
with no gap or overlap" guarantee, same raise-ValueError-on-bad-input
discipline, so the agent endpoint and the UI can treat the two alike.

**Parts are dicts, not a `Part` class.** Everything crossing the agent-API
boundary in this codebase is JSON, and `_assemble_operon` already sets the
precedent (`genes` is a list of dicts). A part is
``{'name': str, 'seq': str, 'type': str?}``; a bare `str` is accepted and
promoted to a part with a positional default name.

**Scrubbing only ever touches the coding block.** Synonymous codon swaps are
safe by construction; a promoter or terminator has no synonymous
representation, so "fixing" a motif there would silently break the part. A
motif that lands in a non-coding part — or straddles a junction such that no
codon swap can clear it — is REPORTED as a residual, never edited. That
asymmetry is the whole safety story of this module.

**Cryptic splice sites are scored, not regexed.** `GT` and `AG` each occur
every ~16 bp by chance, so pattern-matching them flags the whole CDS. The check
delegates to `splicecraft_splice`, whose clade-matched PWMs rank a candidate
against real plant splice sites and against unused GT/AG dinucleotides. Sites
are REPORTED, not auto-edited: clearing one costs a synonymous swap that may
create a different problem, and a donor/acceptor PAIR at intron spacing is a
far stronger signal than either alone. When no model is loaded the check says
so — it never returns an empty list that would read as "clean".

Layer L3: imports state(L0), biology(L0), logging(L0), splice(L0),
dataaccess(L1), codon(L2). Nothing here imports the hub or any L4+ sibling, so
the module is importable from tests and headless agent runs without booting the
app.
"""
